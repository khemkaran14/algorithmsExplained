import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { catalog, type LessonMeta } from '../src/content/catalog';
async function main() {
  const raw = JSON.parse(
    await readFile('content/curriculum.json', 'utf8'),
  ) as LessonMeta[];
  const previous = new Map(catalog.map((l) => [l.slug, l]));
  const entries = raw.map((entry) => ({
    ...entry,
    ...previous.get(entry.slug),
    order: entry.order,
    track: entry.track,
    module: entry.module,
    status: previous.get(entry.slug)?.status ?? entry.status,
  }));
  const groups = new Map<string, typeof entries>();
  for (const entry of entries) {
    const key = `${entry.track}/${entry.module}`;
    groups.set(key, [...(groups.get(key) ?? []), entry]);
  }
  const defaults = new Map<string, boolean>();
  for (const group of groups.values()) {
    group.sort((a, b) => a.order - b.order);
    const count = Math.ceil(group.length * 0.2);
    group.forEach((entry, i) => {
      entry.isFree = i < count;
      defaults.set(entry.slug, entry.isFree);
    });
  }
  const alwaysFree = new Set([
    'big-o',
    'bubble-sort',
    'binary-search',
    'stack',
    'bfs',
    'url-shortener',
  ]);
  for (const entry of entries)
    if (alwaysFree.has(entry.slug)) entry.isFree = true;
  const target = Math.ceil(entries.length * 0.2);
  while (entries.filter((l) => l.isFree).length > target) {
    const removable = [...groups.values()]
      .map((group) => ({
        group,
        excess: group.filter((l) => l.isFree).length - group.length * 0.2,
      }))
      .filter(({ group }) => group.filter((l) => l.isFree).length > 1)
      .sort((a, b) => b.excess - a.excess);
    let removed = false;
    for (const { group } of removable) {
      const candidate = [...group]
        .reverse()
        .find((l) => l.isFree && !alwaysFree.has(l.slug) && l !== group[0]);
      if (candidate) {
        candidate.isFree = false;
        removed = true;
        break;
      }
    }
    if (!removed)
      throw new Error(
        'Cannot satisfy the global free ratio while preserving module samples.',
      );
  }
  let imports =
    "import type {LessonMeta} from './types';\nexport type {LessonMeta} from './types';\n";
  for (const [i, entry] of entries.entries()) {
    const base = path.join('content', entry.track, entry.module, entry.slug);
    await mkdir(base, { recursive: true });
    const override =
      defaults.get(entry.slug) !== entry.isFree
        ? entry.isFree
          ? '// Manual override: keep this flagship lesson free.\n'
          : '// Manual override: adjust rounded module allocation to maintain the global 18–22% free budget; every module retains a free lesson.\n'
        : '';
    await writeFile(
      path.join(base, 'meta.ts'),
      '// Generated by pnpm content:generate-catalog.\n' +
        override +
        'const meta=' +
        JSON.stringify(entry, null, 2) +
        ' as const;\nexport default meta;\n',
    );
    imports += `import lesson${i} from '../../${base}/meta';\n`;
  }
  imports +=
    'export const catalog:readonly LessonMeta[]=[' +
    entries.map((_, i) => `lesson${i}`).join(',') +
    '];\nexport function lessonUrl(l:LessonMeta){return `/learn/${l.track}/${l.module}/${l.slug}`}\n';
  await writeFile('src/content/catalog.ts', imports);
  console.log(
    `Catalog: ${entries.length} lessons, ${entries.filter((l) => l.isFree).length} free, ${entries.filter((l) => l.status === 'ready').length} ready.`,
  );
}
void main();
