import 'server-only';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { run, compile } from '@mdx-js/mdx';
import * as runtime from 'react/jsx-runtime';
import { codeToTokens } from 'shiki';
import { catalog, type LessonMeta } from './catalog';
import { LANGUAGES, type Lang } from '@/engine/types';
export type CodeToken = { content: string; color?: string };
export type CodeLines = Record<Lang, CodeToken[][]>;
export type QuizQuestion = {
  id: string;
  question: string;
  choices: string[];
  answer: number;
  explanation: string;
};
const files: Record<Lang, string> = {
  javascript: 'js.ts',
  python: 'py.py',
  java: 'java.java',
  cpp: 'cpp.cpp',
};
export async function loadLesson(meta: LessonMeta) {
  // Callers MUST authorize before invoking this loader. Public metadata is separate.
  if (
    !catalog.some(
      (l) =>
        l.slug === meta.slug &&
        l.module === meta.module &&
        l.track === meta.track,
    )
  )
    throw new Error('Unknown lesson');
  const base = path.join(
    process.cwd(),
    'content',
    meta.track,
    meta.module,
    meta.slug,
  );
  const source = await readFile(path.join(base, 'lesson.mdx'), 'utf8');
  const compiled = await compile(source, { outputFormat: 'function-body' });
  const { default: Content } = await run(String(compiled), {
    ...runtime,
    baseUrl: import.meta.url,
  });
  const code = {} as CodeLines;
  for (const lang of LANGUAGES) {
    const text = await readFile(path.join(base, 'code', files[lang]), 'utf8');
    const tokens = await codeToTokens(text, { lang, theme: 'github-dark' });
    code[lang] = tokens.tokens.map((line) =>
      line.map((t) => ({ content: t.content, color: t.color })),
    );
  }
  // Explicit import paths are generated by the content index, never from request input.
  const quiz = (await quizLoaders[meta.slug]()).default as QuizQuestion[];
  return { Content, code, quiz };
}
const quizLoaders: Record<string, () => Promise<{ default: QuizQuestion[] }>> =
  {
    'big-o': () => import('../../content/dsa/foundations/big-o/quiz'),
    'bubble-sort': () => import('../../content/dsa/sorting/bubble-sort/quiz'),
    'binary-search': () =>
      import('../../content/dsa/searching/binary-search/quiz'),
    stack: () => import('../../content/dsa/linear/stack/quiz'),
    bfs: () => import('../../content/dsa/graphs/bfs/quiz'),
  };
